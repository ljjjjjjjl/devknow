-- ============================================================================
--  V7__add_conversation_summary.sql  ·  上下文摘要压缩（第 8 周）
-- ============================================================================
--  目的：长会话超出上下文窗口时，不再把早期对话"直接丢掉"，而是先压成一段
--        定长摘要留在 conversation 上，之后每轮随请求带上。
--
--  为什么放两列而不建新表：
--   · 摘要与会话是 1:1，且永远只有"当前那一段"，没有历史版本要留
--   · 滚动重写而不是追加，所以不需要一张按时间增长的摘要表
--
--  summary_upto_seq 是水位线：记录"已经压到第几条消息"（conversation_message.seq）。
--  没有它，同一段对话会在每次超出预算时被反复压缩 —— 既费钱，又会让摘要
--  被反复改写从而丢掉早期信息。0 表示从未压过。
--
--  ⚠️ 与 loadContext 的关系：摘要只覆盖"被窗口丢掉的那一段"，与原文窗口
--  永不重叠；重叠的话模型会看到同一句话两遍，还会自相矛盾。
-- ============================================================================

ALTER TABLE conversation
    ADD COLUMN summary          TEXT,
    ADD COLUMN summary_upto_seq INT NOT NULL DEFAULT 0;

COMMENT ON COLUMN conversation.summary          IS '更早对话的滚动摘要；NULL 表示还没压过';
COMMENT ON COLUMN conversation.summary_upto_seq IS '摘要已覆盖到的消息 seq（水位线），0 = 从未压缩';
